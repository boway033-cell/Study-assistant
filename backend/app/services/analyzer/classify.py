def classify_local(title: str, keywords: list[str], chapters: list[str] | None = None) -> str:
    """本地关键词匹配分类。

    Args:
        title: 书名
        keywords: jieba 提取的关键词列表
        chapters: 章节标题列表（可选，增加匹配面）
    Returns:
        类别名（数学/管理学/.../其他）
    """
    # 汇总文本特征
    text_parts = [title] + (keywords or []) + (chapters or [])
    combined = " ".join(str(p) for p in text_parts)

    scores: dict[str, float] = {}
    for cat, seeds in _SEEDS.items():
        hits = 0
        for seed in seeds:
            seed_clean = seed.strip()
            if seed_clean in combined:
                hits += 1
        # 归一化：命中数 / 种子数（Jaccard 近似）
        if hits > 0:
            scores[cat] = hits / max(len(seeds), 1)

    if not scores:
        return "其他"

    # 取最高分，且需达到最低阈值
    best_cat = max(scores, key=scores.get)
    if scores[best_cat] < 0.03:
        return "其他"
    return best_cat


