export function getSolarTerm(date = new Date()) {
  const m = date.getMonth() + 1
  const d = date.getDate()
  let cur = TERMS[0]
  for (const t of TERMS) {
    if (m > t.m || (m === t.m && d >= t.d)) cur = t
  }
  const hou = HOU[cur.name] || ['一候', '二候', '三候']
  return { name: cur.name, poem: cur.poem, hou }
}
